#!/usr/bin/env python3
"""Infrahub object files for the device types and module types.

Reads the committed NetBox trees (`library/exports/netbox/device-types` and
`module-types`) and writes, into the folder `--out` names:

    schema/portrayal-overlay.yml   the two-attribute overlay (design note, 3.9)
    README.md                      the schema files to load in sequence, the rules
                                   and what is left out, with this run's counts
    objects/00-manufacturers.yml   one OrganizationManufacturer per maker
    objects/<maker>.yml            that maker's DcimDeviceType and DcimModuleType

Nothing is written under `library/exports` by default and nothing this tool
writes is committed: `--out` has no default. The NetBox tree is the single
source, so the Infrahub files agree with it one to one. The mapping, the key rule
and the open questions are in `docs/infrahub-export-design.md`.

Rules, each stated again in the README it writes:

* A type's `name` is `<manufacturer> <model>`: a bare model is not unique across
  makers (the same hardware is listed under several NOS makers).
* `height` is the NetBox `u_height` rounded up, because Infrahub holds a whole
  number; a half-unit type says its nominal height in its description. A type
  with `u_height` 0 is written without `height`.
* A device type's `weight` is whole kilograms (rounded) and `weight_grams` is
  exact; a module type has `weight_grams` only.

Unverified: the file shape and the overlay were taken from the design note and
not loaded into an Infrahub instance.
"""
import argparse
import math
import re
import sys
from pathlib import Path

import yaml

_LOADER = getattr(yaml, "CSafeLoader", yaml.SafeLoader)

MANUFACTURERS_FILE = "00-manufacturers.yml"
GRAMS = {"kg": 1000, "g": 1, "lb": 453.59237, "oz": 28.349523125}
# Ports a device type has that Infrahub holds no node for on a type (note, 3.5).
UNHELD_PORTS = (("console-ports", "console port"),
                ("console-server-ports", "console server port"),
                ("power-ports", "power port"), ("power-outlets", "power outlet"))

OVERLAY = """\
# Portrayal overlay, loaded after the library files. Unverified: whether an
# `extensions` block may add an attribute to an existing node has not been
# checked against an Infrahub instance (design note, question 7).
extensions:
  nodes:
    - kind: InterfacePhysical
      attributes:
        - name: port_type
          kind: Text
          optional: true
    - kind: DcimDeviceType
      attributes:
        - name: weight_grams
          kind: Number
          optional: true
"""

README = """\
# Infrahub object files: device types and module types

Generated by `spec/tools/dev/infrahub_export.py` from the NetBox export
tree. Do not edit by hand; run the tool again.

This run wrote {makers} manufacturers, {devices} device types and {modules}
module types.

## Load sequence

Load the schema files first, in this sequence, from OpsMill's schema library
(`https://github.com/opsmill/schema-library`; the design note names commit
`26336e9026dff1907f2c58e81dd6ae7b5c3f763e`):

1. `base/organization.yml`
2. `base/location.yml`
3. `base/ipam.yml` (`base/dcim.yml` names `IpamIPAddress` as a peer)
4. `base/dcim.yml`
5. `extensions/location_site/location_site.yml`
6. `extensions/rack/rack.yml`
7. `extensions/cable/cable.yml`
8. `extensions/device_module/device_module.yml`
9. `extensions/module_port/module_port.yml`
10. `extensions/patch_panel/patch_panel.yml`
11. `schema/portrayal-overlay.yml` (this folder)

with `infrahubctl schema load`. Then the objects, with `infrahubctl object load`,
file by file, the manufacturers first:

1. `objects/{manufacturers_file}`
2. every other file in `objects/`, in any sequence

Each maker's file holds two documents, separated by `---`: its `DcimDeviceType`
objects, then its `DcimModuleType` objects (a maker with only one kind has one
document).

## The key

A type's `name` is `<manufacturer> <model>`, for example `Juniper MX104`. It is
the key a later load matches on, so it must not change: a type loaded under a
different name is a second type in the instance. A bare model is not used because
`DcimDeviceType.name` is unique across every maker and the same hardware is listed
under several NOS makers with the same model. The slug is not written.

## Rounding and what a number means

- `height` is the `u_height` rounded up to a whole number, which keeps a rack from
  being over-filled on paper. {halves} device types are half-unit types; each says
  its nominal height in its description ("3.5 U nominal").
- {zero_u} device types have `u_height` 0 (a box not in a rack). They are written
  without `height`, so the schema default applies; the schema does not say what
  a default of 1 means for a zero-U part.
{zero_u_names}
- A device type's `weight` is the weight in whole kilograms, rounded, so a light
  device reads as 0 kg. `weight_grams` beside it is exact. {fractional_devices}
  device types and {fractional_modules} module types have a fractional weight.
- A module type has `weight_grams` only (the library's own attribute).
- The description of a device type that has console ports, power ports or power
  outlets says how many; there is no node for them on a type, so they are not
  exported.

## Unverified

- The object file shape (`apiVersion: infrahub.app/v1`, `kind: Object`,
  `spec: {{kind, data}}`) is the design note's. Assumed where the note is silent:
  `data` is a list; a type's manufacturer is its name as a plain string; one file
  holds several documents; `height` may be absent.
- The overlay is as the design note gives it. Whether an `extensions` block may add
  an attribute to an existing node is unverified. If your instance rejects the
  overlay, load the files without `weight_grams`: remove that line from each
  `DcimDeviceType` object and skip `schema/portrayal-overlay.yml`.
- The test fixture for the schema is taken from `docs/infrahub-export-design.md`,
  not from the schema library; it is unchecked against the commit named above.
- No load into an Infrahub instance was done. Before relying on the files, run
  `infrahubctl schema check`, `infrahubctl schema load --wait`, then
  `infrahubctl object validate` and `infrahubctl object load` on a real instance.

## Left out

Racks, placed devices, interfaces (in this schema an interface exists only on a
placed device), cables, type-level ports and module bays, drawings, console and
power ports, comments, airflow, the slug, the weight unit and dimensions other
than height and full depth.
"""


def load(path):
    return yaml.load(path.read_text(encoding="utf-8"), Loader=_LOADER)


def read_tree(netbox, folder):
    """The documents of one NetBox folder, sorted by path."""
    return [load(p) for p in sorted((netbox / folder).glob("*/*.yaml"))]


def grams(doc):
    """The weight in grams, rounded to a whole number, or None."""
    weight = doc.get("weight")
    if weight is None:
        return None
    return round(weight * GRAMS[doc.get("weight_unit", "kg")])


def type_name(doc):
    return f"{doc['manufacturer']} {doc['model']}"


def device_entry(doc):
    u = doc.get("u_height") or 0
    parts = [(doc.get("description") or "").strip()]
    if u and u != int(u):
        parts.append(f"({u:g} U nominal)")
    held = [f"{len(doc[key])} {noun}{'' if len(doc[key]) == 1 else 's'}"
            for key, noun in UNHELD_PORTS if doc.get(key)]
    if held:
        parts.append(f"Has {' and '.join(held)}; not exported.")
    entry = {"name": type_name(doc), "manufacturer": doc["manufacturer"]}
    if doc.get("part_number"):
        entry["part_number"] = str(doc["part_number"])
    description = " ".join(p for p in parts if p)
    if description:
        entry["description"] = description
    if u:
        entry["height"] = math.ceil(u)
    entry["full_depth"] = bool(doc.get("is_full_depth", True))
    g = grams(doc)
    if g is not None:
        entry["weight"] = math.floor(g / 1000 + 0.5)
        entry["weight_grams"] = g
    return entry


def module_entry(doc):
    entry = {"name": type_name(doc), "manufacturer": doc["manufacturer"]}
    if doc.get("part_number"):
        entry["part_number"] = str(doc["part_number"])
    if doc.get("description"):
        entry["description"] = doc["description"].strip()
    g = grams(doc)
    if g is not None:
        entry["weight_grams"] = g
    return entry


def object_doc(kind, data):
    return {"apiVersion": "infrahub.app/v1", "kind": "Object",
            "spec": {"kind": kind, "data": sorted(data, key=lambda e: e["name"])}}


def dump(docs):
    return yaml.safe_dump_all(docs, sort_keys=False, allow_unicode=True, width=10 ** 6,
                              explicit_start=True)


def file_name(maker):
    return re.sub(r"[^A-Za-z0-9._+ -]", "_", maker) + ".yml"


def build(netbox):
    """Everything to write, as ({maker: [docs]}, manufacturers, counts)."""
    devices = read_tree(netbox, "device-types")
    modules = read_tree(netbox, "module-types")
    by_maker = {}
    for kind, entry_of, docs in (("DcimDeviceType", device_entry, devices),
                                 ("DcimModuleType", module_entry, modules)):
        grouped = {}
        for d in docs:
            grouped.setdefault(d["manufacturer"], []).append(entry_of(d))
        names = [e["name"] for rows in grouped.values() for e in rows]
        if len(names) != len(set(names)):
            raise ValueError(f"a {kind} name is not unique")
        for maker, rows in grouped.items():
            by_maker.setdefault(maker, []).append(object_doc(kind, rows))
    files = {}
    for maker in by_maker:
        name = file_name(maker)
        if name.lower() in {n.lower() for n in files} | {MANUFACTURERS_FILE}:
            raise ValueError(f"two makers share the file name {name}")
        files[name] = by_maker[maker]
    zero_u = sorted(type_name(d) for d in devices if not d.get("u_height"))
    counts = {
        "makers": len(by_maker), "devices": len(devices), "modules": len(modules),
        "halves": sum(1 for d in devices if (d.get("u_height") or 0) % 1),
        "zero_u": len(zero_u),
        "fractional_devices": sum(1 for d in devices if d.get("weight") is not None and d["weight"] % 1),
        "fractional_modules": sum(1 for d in modules if d.get("weight") is not None and d["weight"] % 1),
    }
    return files, sorted(by_maker), zero_u, counts


def write(netbox, out):
    files, makers, zero_u, counts = build(netbox)
    (out / "objects").mkdir(parents=True, exist_ok=True)
    (out / "schema").mkdir(parents=True, exist_ok=True)
    manufacturers = object_doc("OrganizationManufacturer", [{"name": m} for m in makers])
    (out / "objects" / MANUFACTURERS_FILE).write_text(dump([manufacturers]), encoding="utf-8")
    for name, docs in files.items():
        (out / "objects" / name).write_text(dump(docs), encoding="utf-8")
    (out / "schema" / "portrayal-overlay.yml").write_text(OVERLAY, encoding="utf-8")
    names = "".join(f"  - {n}\n" for n in zero_u)
    (out / "README.md").write_text(
        README.format(manufacturers_file=MANUFACTURERS_FILE, zero_u_names=names, **counts),
        encoding="utf-8")
    return counts


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--netbox", type=Path, default=Path("library/exports/netbox"),
                    help="the NetBox export tree to read (default: %(default)s)")
    ap.add_argument("--out", type=Path, required=True,
                    help="the folder to write into; there is no default")
    args = ap.parse_args(argv)
    counts = write(args.netbox, args.out)
    print(", ".join(f"{k}={v}" for k, v in counts.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
